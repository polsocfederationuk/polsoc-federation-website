#!/usr/bin/env node
/**
 * build-identity.js — bundle @netlify/identity for the staff login page.
 *
 * WHY A BUNDLE STEP EXISTS AT ALL
 *
 * @netlify/identity is a library, not a script tag. Its ESM build imports
 * gotrue-js, so a browser cannot load it directly, and every other script in
 * this repository is hand-written and embedded inline precisely because there
 * was nothing to bundle. This is the first real dependency the browser needs.
 *
 * SELF-HOSTED, NOT A CDN
 *
 * The previous implementation loaded the legacy Netlify Identity Widget from
 * identity.netlify.com. Bundling instead means:
 *
 *   - the version is PINNED by package-lock, not whatever the CDN serves today
 *   - the login page loads no third-party script, so its Content-Security-Policy
 *     no longer needs a foreign script origin
 *   - the page works from the same origin as everything else it talks to
 *
 * The output is written into src/admin/ as a generated file and passed through
 * to the built site, so the local CMS build and the production build both get
 * the same bytes.
 *
 * Run:  node scripts/build-identity.js       (or: npm run build:identity)
 */

"use strict";

const fs = require("fs");
const path = require("path");
const esbuild = require("esbuild");

const ROOT = path.join(__dirname, "..");
const OUT = path.join(ROOT, "src", "admin", "netlify-identity.bundle.js");

const version = require(
  path.join(ROOT, "node_modules", "@netlify", "identity", "package.json")).version;

/*
  An IIFE on `window.netlifyIdentityApi`, not an ES module.

  The login page embeds its script inline — there is no module graph to import
  into — and a global is the simplest thing that works with a strict CSP and no
  import map. The name is deliberately NOT `netlifyIdentity`: that is what the
  legacy widget called itself, and two different APIs answering to one name is
  how somebody ends up calling `.open()` on a library that has no such method.
*/
esbuild.buildSync({
  stdin: {
    /*
      ONLY WHAT THE LOGIN PAGE CALLS.

      A wildcard re-export also drags in the SERVER-side helpers —
      verifyRequestOrigin, the admin user-management calls — which the browser
      has no use for. None of them is a secret and none grants anything on its
      own, but a browser bundle should carry what the page needs rather than a
      catalogue of what the package can do. Naming the exports also makes this
      a readable list of the API the login page is allowed to use.
    */
    contents: [
      "export {",
      "  getSettings, getUser, handleAuthCallback, hydrateSession,",
      "  login, logout, oauthLogin, acceptInvite, updateUser,",
      "  requestPasswordRecovery, AuthError, MissingIdentityError,",
      '} from "@netlify/identity";',
    ].join("\n"),
    resolveDir: ROOT,
    sourcefile: "netlify-identity-entry.js",
  },
  bundle: true,
  format: "iife",
  globalName: "netlifyIdentityApi",
  platform: "browser",
  target: ["es2019"],
  minify: true,
  legalComments: "none",
  outfile: OUT,
  banner: {
    js: `/* GENERATED by scripts/build-identity.js from @netlify/identity@${version}.\n` +
      `   Do not edit. Rebuild with: npm run build:identity */`,
  },
});

const bytes = fs.statSync(OUT).size;

/*
  The bundle must not have dragged a build-time secret or a Node built-in into
  the browser. esbuild would normally fail loudly on the latter, but this is
  cheap and the file is about to be served publicly.
*/
const text = fs.readFileSync(OUT, "utf8");
const problems = [];
if (/CMS_GITHUB|PRIVATE KEY|ghp_|nfp_/.test(text)) problems.push("contains something secret");
if (/require\(["']fs["']\)|process\.env\.[A-Z_]*KEY/.test(text)) {
  problems.push("references Node internals or a key");
}
if (!/netlifyIdentityApi/.test(text)) problems.push("does not define the global");

if (problems.length) {
  console.error("\n  IDENTITY BUNDLE REFUSED");
  for (const p of problems) console.error(`  ✗ ${p}`);
  process.exit(1);
}

console.log(`  @netlify/identity@${version} bundled -> ` +
  `src/admin/netlify-identity.bundle.js (${Math.round(bytes / 1024)} kB)`);
